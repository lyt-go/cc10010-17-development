"""示例数据：每个模块给几条不同状态的记录，方便起服务后立刻看到内容。

基线时间线依赖相对时间，示例数据统一以服务启动当天为锚点生成，
这样无论哪天拉起服务，都能看到预警中、已破线和待观测三种状态。
"""
from __future__ import annotations

from datetime import datetime, timedelta
from typing import Any


def _day_at(day_offset: int, hour: int, minute: int = 0) -> str:
    base = datetime.now() + timedelta(days=day_offset)
    return base.replace(hour=hour, minute=minute, second=0, microsecond=0).strftime("%Y-%m-%d %H:%M")


def _today(hour: int, minute: int = 0) -> str:
    return _day_at(0, hour, minute)


def _yesterday(hour: int, minute: int = 0) -> str:
    return _day_at(-1, hour, minute)


def _at(delta_minutes: int) -> str:
    """按“距服务启动时刻多少分钟”生成时间，保证示例场景每天都能成立。"""
    moment = datetime.now() + timedelta(minutes=delta_minutes)
    return moment.replace(second=0, microsecond=0).strftime("%Y-%m-%d %H:%M")


def _today_date() -> str:
    return datetime.now().strftime("%Y-%m-%d")


